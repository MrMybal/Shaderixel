def make_torus_glb(path, R=1.0, r=0.38, seg=96, ring=48):
    """Torus with clean UVs (good for 3D painting)."""
    pos, nrm, uv, idx = [], [], [], []
    for i in range(seg + 1):
        u = i / seg
        a = u * 2 * math.pi
        for j in range(ring + 1):
            v = j / ring
            b = v * 2 * math.pi
            cx, cz = math.cos(a), math.sin(a)
            nx, ny, nz = math.cos(b) * cx, math.sin(b), math.cos(b) * cz
            pos.append(((R + r * math.cos(b)) * cx, r * math.sin(b), (R + r * math.cos(b)) * cz))
            nrm.append((nx, ny, nz))
            uv.append((u, v))
    for i in range(seg):
        for j in range(ring):
            a0 = i * (ring + 1) + j
            a1 = (i + 1) * (ring + 1) + j
            idx += [a0, a0 + 1, a1, a1, a0 + 1, a1 + 1]
    blob = b''.join(struct.pack('<3f', *p) for p in pos)
    blob += b''.join(struct.pack('<3f', *n) for n in nrm)
    blob += b''.join(struct.pack('<2f', *t) for t in uv)
    blob += b''.join(struct.pack('<I', k) for k in idx)
    n = len(pos)
    o_n, o_t, o_i = n * 12, n * 24, n * 32
    mins = [min(p[k] for p in pos) for k in range(3)]
    maxs = [max(p[k] for p in pos) for k in range(3)]
    g = {
        'asset': {'version': '2.0', 'generator': 'Shaderixel package.py'},
        'scene': 0, 'scenes': [{'nodes': [0]}], 'nodes': [{'mesh': 0, 'name': 'Tore'}],
        'meshes': [{'primitives': [{'attributes': {'POSITION': 0, 'NORMAL': 1, 'TEXCOORD_0': 2}, 'indices': 3}]}],
        'accessors': [
            {'bufferView': 0, 'componentType': 5126, 'count': n, 'type': 'VEC3', 'min': mins, 'max': maxs},
            {'bufferView': 1, 'componentType': 5126, 'count': n, 'type': 'VEC3'},
            {'bufferView': 2, 'componentType': 5126, 'count': n, 'type': 'VEC2'},
            {'bufferView': 3, 'componentType': 5125, 'count': len(idx), 'type': 'SCALAR'}],
        'bufferViews': [
            {'buffer': 0, 'byteOffset': 0, 'byteLength': n * 12},
            {'buffer': 0, 'byteOffset': o_n, 'byteLength': n * 12},
            {'buffer': 0, 'byteOffset': o_t, 'byteLength': n * 8},
            {'buffer': 0, 'byteOffset': o_i + 0, 'byteLength': len(idx) * 4}],
        'buffers': [{'byteLength': len(blob)}]}
    # Fix offsets: normals start after positions, uvs after normals, indices after uvs.
    g['bufferViews'][2]['byteOffset'] = n * 24
    g['bufferViews'][3]['byteOffset'] = n * 32
    js = json.dumps(g).encode()
    js += b' ' * ((4 - len(js) % 4) % 4)
    blob += bytes((4 - len(blob) % 4) % 4)
    glb = b'glTF' + struct.pack('<II', 2, 12 + 8 + len(js) + 8 + len(blob))
    glb += struct.pack('<I', len(js)) + b'JSON' + js
    glb += struct.pack('<I', len(blob)) + bytes([0x42, 0x49, 0x4E, 0x00]) + blob
    with open(path, 'wb') as f:
        f.write(glb)



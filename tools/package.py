def make_mug_obj(path, seg=96):
    """Mug with a handle, positions and normals only (no UVs: the example unwraps it with xatlas)."""
    verts, norms, faces = [], [], []

    def revolve(profile):
        # profile: list of (radius, y) from outside bottom over the rim to inside bottom; smooth normals per ring.
        base = len(verts)
        n = len(profile)
        for i, (r, y) in enumerate(profile):
            # Normal of the profile curve (2D), rotated around Y.
            r0, y0 = profile[max(i - 1, 0)]
            r1, y1 = profile[min(i + 1, n - 1)]
            tr, ty = r1 - r0, y1 - y0
            nr, ny = ty, -tr
            ln = math.hypot(nr, ny) or 1.0
            nr, ny = nr / ln, ny / ln
            for s in range(seg):
                a = 2 * math.pi * s / seg
                verts.append((r * math.cos(a), y, r * math.sin(a)))
                norms.append((nr * math.cos(a), ny, nr * math.sin(a)))
        for i in range(n - 1):
            for s in range(seg):
                a, b = base + i * seg + s, base + i * seg + (s + 1) % seg
                c, d = base + (i + 1) * seg + s, base + (i + 1) * seg + (s + 1) % seg
                faces.append((a, c, b))
                faces.append((b, c, d))

    # Outside (bottom center -> rounded foot -> wall -> rounded rim), then inside down to the inner bottom.
    prof = [(0.0, 0.0), (0.30, 0.0), (0.38, 0.015), (0.40, 0.05)]
    for k in range(1, 12):
        t = k / 12.0
        prof.append((0.40 + 0.03 * math.sin(t * math.pi), 0.05 + 0.85 * t))
    prof += [(0.43, 0.92), (0.425, 0.95), (0.40, 0.955), (0.375, 0.945)]
    for k in range(1, 10):
        t = k / 10.0
        prof.append((0.375 + 0.02 * math.sin((1 - t) * math.pi), 0.94 - 0.84 * t))
    prof += [(0.34, 0.09), (0.2, 0.08), (0.0, 0.08)]
    revolve(prof)
    # Handle: a tube along an arc on the +X side.
    base = len(verts)
    rings, sides, R, r = 40, 16, 0.24, 0.045
    cx, cy = 0.42, 0.5
    arc = []
    for i in range(rings + 1):
        a = -math.pi * 0.42 + math.pi * 0.84 * i / rings
        arc.append((cx + R * math.cos(a) * 0.9, cy + R * math.sin(a) * 1.25))
    for i, (px, py) in enumerate(arc):
        qx, qy = arc[min(i + 1, rings)]
        ox, oy = arc[max(i - 1, 0)]
        tx, ty = qx - ox, qy - oy
        lt = math.hypot(tx, ty)
        tx, ty = tx / lt, ty / lt
        nx, ny = -ty, tx
        for s in range(sides):
            b = 2 * math.pi * s / sides
            dx, dy, dz = nx * math.cos(b), ny * math.cos(b), math.sin(b)
            verts.append((px + dx * r, py + dy * r, dz * r * 1.4))
            norms.append((dx, dy, dz))
    for i in range(rings):
        for s in range(sides):
            a, b = base + i * sides + s, base + i * sides + (s + 1) % sides
            c, d = base + (i + 1) * sides + s, base + (i + 1) * sides + (s + 1) % sides
            faces.append((a, b, c))
            faces.append((b, d, c))
    with open(path, 'w') as f:
        f.write('# Mug: no UV coordinates (unwrapped with xatlas in Shaderixel)' + chr(10) + 'o Tasse' + chr(10))
        for v in verts:
            f.write('v %.5f %.5f %.5f\n' % v)
        for n in norms:
            f.write('vn %.5f %.5f %.5f\n' % n)
        for a, b, c in faces:
            f.write('f %d//%d %d//%d %d//%d\n' % (a + 1, a + 1, b + 1, b + 1, c + 1, c + 1))


def main():
    if '--no-build' not in sys.argv:
        run_build()
    date = datetime.date.today().strftime('%Y%m%d')
    name = 'Shaderixel-' + date
    dist = os.path.join(ROOT, 'dist', name)
    if os.path.exists(dist):
        shutil.rmtree(dist)
    os.makedirs(dist)
    for f in os.listdir(BUILD):
        if f.lower().endswith(('.exe', '.dll')):
            shutil.copy2(os.path.join(BUILD, f), dist)
    shutil.copytree(os.path.join(ROOT, 'shaders'), os.path.join(dist, 'shaders'))
    # Skills for AI assistants (Claude Code, other agents): writing effects in HLSL, importing them.
    shutil.copytree(os.path.join(ROOT, '.claude', 'skills'), os.path.join(dist, 'IA', 'skills'))
    # Python helpers run by the app (Select > Subject).
    shutil.copytree(os.path.join(ROOT, 'tools', 'ai'), os.path.join(dist, 'ai'))
    # Third-party licenses (libraries built in or shipped).
    lic = os.path.join(dist, 'licences')
    os.makedirs(lic, exist_ok=True)
    for lib in ('imgui', 'stb', 'slang', 'volk', 'vulkan-headers', 'xatlas'):
        base = os.path.join(ROOT, 'external', lib)
        for f in ('LICENSE', 'LICENSE.txt', 'LICENSE.md'):
            if os.path.exists(os.path.join(base, f)):
                shutil.copy2(os.path.join(base, f), os.path.join(lic, lib + '_' + f))
        if os.path.isdir(os.path.join(base, 'LICENSES')):
            shutil.copytree(os.path.join(base, 'LICENSES'), os.path.join(lic, lib + '_LICENSES'))
    ex = os.path.join(dist, 'Exemples')
    shots = os.path.join(dist, 'Guide_images')
    os.makedirs(ex)
    os.makedirs(shots)
    shutil.copy2(os.path.join(ROOT, 'assets', 'logo.png'), os.path.join(shots, 'logo.png'))

    exe = os.path.join(dist, 'Shaderixel.exe')
    work = os.path.join(dist, '_work')
    os.makedirs(work)
    for fname, demo, frames, title, _ in EXAMPLES:
        args = [exe, '--demo'] + ([demo] if demo else []) + ['--frames', str(frames),
                '--capture', os.path.join(shots, fname + '.png'), '--save', os.path.join(ex, fname + '.sxl')]
        print('Example', fname)
        subprocess.run(args, cwd=work, timeout=300)
    # Layered PSD and the sample assets written by demos.
    subprocess.run([exe, '--demo', 'psd', '--frames', '80', '--capture', os.path.join(work, 'x.png')], cwd=work, timeout=300)
    subprocess.run([exe, '--demo', 'hdri', '--frames', '30', '--capture', os.path.join(shots, '14_HDRI.png')], cwd=work, timeout=300)
    subprocess.run([exe, '--demo', 'genfill', '--frames', '45', '--capture', os.path.join(shots, '15_Remplissage_generatif.png')],
                   cwd=work, timeout=300, env=dict(os.environ, SX_AI_MOCK='1'))
    for src, dst in [('demo_export.psd', 'Calques_Photoshop.psd'), ('demo_grade.cube', 'LUT_Sarcelle_Orange.cube'), ('demo_sky.hdr', 'Ciel.hdr')]:
        if os.path.exists(os.path.join(work, src)):
            shutil.copy2(os.path.join(work, src), os.path.join(ex, dst))
    make_torus_glb(os.path.join(ex, 'Tore.glb'))
    # Paint 3D example: a mug without UVs (unwrapped by xatlas at creation), gold rim material,
    # waves on a paint layer, logo projected with the Projection tool.
    make_mug_obj(os.path.join(ex, 'Tasse.obj'))
    print('Example 16_Tasse_Paint3D')
    subprocess.run([exe, '--demo', 'example3d', '--frames', '40', '--capture', os.path.join(shots, '16_Tasse_Paint3D.png')], cwd=work, timeout=300,
                   env=dict(os.environ, SX_MESHFILE=os.path.join(ex, 'Tasse.obj'), SX_DECAL=os.path.join(ROOT, 'assets', 'logo.png'),
                            SX_OUT=os.path.join(ex, '16_Tasse_Paint3D.sx3d')))
    # Render mode on that project (path traced, glass sphere and gold cube added for the picture).
    print('Render 16_Tasse_Paint3D')
    subprocess.run([exe, '--demo', 'render', '--frames', '200', '--focus', 'Rendu', '--capture', os.path.join(shots, '16_Tasse_Rendu.png'),
                    os.path.join(ex, '16_Tasse_Paint3D.sx3d')], cwd=work, timeout=300, env=dict(os.environ, SX_SCENE='1', SX_SAMPLES='512'))
    shutil.rmtree(work, ignore_errors=True)
    # Runtime files the demos left next to the exe.
    for f in os.listdir(dist):
        if f.endswith(('.log', '.ini', '.txt', '.json')) and f != 'LISEZMOI.txt':
            os.remove(os.path.join(dist, f))

    with open(os.path.join(ROOT, 'tools', 'guide_template.html'), encoding='utf-8') as f:
        html = f.read()
    cards = []
    for fname, demo, frames, title, tip in EXAMPLES:
        cards.append(f'''<article class="ex"><img src="Guide_images/{fname}.png" alt="{title}" loading="lazy">
<div><h3>{title}</h3><p class="file">Exemples/{fname}.sxl</p><p>{tip}</p></div></article>''')
    html = html.replace('{{EXAMPLES}}', '\n'.join(cards)).replace('{{DATE}}', datetime.date.today().strftime('%d/%m/%Y'))
    with open(os.path.join(dist, 'Guide.html'), 'w', encoding='utf-8') as f:
        f.write(html)
    with open(os.path.join(dist, 'Lancer Shaderixel (Vulkan).bat'), 'w', encoding='utf-8') as f:
        f.write('@echo off\r\nstart "" "%~dp0ShaderixelVk.exe" %*\r\n')

    z = os.path.join(ROOT, 'dist', name + '.zip')
    if os.path.exists(z):
        os.remove(z)
    with zipfile.ZipFile(z, 'w', zipfile.ZIP_DEFLATED) as zf:
        for base, _, files in os.walk(dist):
            for f in files:
                p = os.path.join(base, f)
                zf.write(p, os.path.join(name, os.path.relpath(p, dist)))
    size = sum(os.path.getsize(os.path.join(b, f)) for b, _, fs in os.walk(dist) for f in fs)
    print(f'Package: {dist} ({size / 1e6:.0f} MB), zip: {z} ({os.path.getsize(z) / 1e6:.0f} MB)')


if __name__ == '__main__':
    main()

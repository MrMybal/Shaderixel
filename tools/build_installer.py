"""Build a per-user Windows installer from a Shaderixel example package.

Requires Inno Setup 7 (ISCC.exe) and the Visual Studio x64 redistributable CRT.
The application is rebuilt before staging. No compiler is downloaded by this tool.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
CONTENT_DIRS = (
    'ai', 'assets', 'functions', 'IA', 'lang', 'layouts', 'licences', 'plugins',
    'scenes', 'SDK', 'shaders', 'smartmaterials', 'swatches', 'templates',
    'Unreal', 'Exemples', 'examples',
)
BINARIES = ('Shaderixel.exe', 'ShaderixelVk.exe', 'dxcompiler.dll', 'dxil.dll',
            'slang.dll', 'slang-compiler.dll', 'slang-glslang.dll', 'slang-rt.dll')


def find_crt():
    vswhere = Path(os.environ.get('ProgramFiles(x86)', 'C:/Program Files (x86)')) / 'Microsoft Visual Studio/Installer/vswhere.exe'
    vs = subprocess.check_output([str(vswhere), '-latest', '-products', '*',
                                 '-requires', 'Microsoft.VisualStudio.Component.VC.Tools.x86.x64',
                                 '-property', 'installationPath'], text=True).strip()
    redist = Path(vs) / 'VC/Redist/MSVC'
    versions = sorted((p for p in redist.iterdir() if re.fullmatch(r'\d+(\.\d+)+', p.name)),
                      key=lambda p: tuple(int(x) for x in p.name.split('.')), reverse=True)
    for version in versions:
        crt = version / 'x64/Microsoft.VC143.CRT'
        if (crt / 'msvcp140.dll').is_file():
            return crt
    raise SystemExit('Visual Studio x64 Microsoft.VC143.CRT redistributables were not found; use --crt-dir.')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--package', required=True, type=Path, help='Folder generated by tools/package.py')
    parser.add_argument('--version', required=True, help='For example: 0.1.0-alpha.20261103')
    parser.add_argument('--iscc', type=Path, help='Path to Inno Setup 7 ISCC.exe; otherwise use PATH')
    parser.add_argument('--crt-dir', type=Path, help='Visual Studio x64 Microsoft.VC143.CRT folder')
    args = parser.parse_args()
    if not re.fullmatch(r'\d+\.\d+\.\d+-alpha\.[A-Za-z0-9._-]+', args.version):
        parser.error('Expected an alpha version such as 0.1.0-alpha.20261103')
    if args.version != (ROOT / "VERSION").read_text(encoding="ascii").strip():
        parser.error("Installer version must match VERSION.")
    package = args.package.resolve()
    for relative in ('LICENSE', 'shaders', 'functions', 'lang/en.json'):
        if not (package / relative).exists():
            parser.error('Missing package content: ' + relative)
    iscc = args.iscc.resolve() if args.iscc else shutil.which('ISCC.exe')
    if not iscc or not Path(iscc).is_file():
        parser.error('Inno Setup 7 is required; supply --iscc or put ISCC.exe on PATH.')
    crt = args.crt_dir.resolve() if args.crt_dir else find_crt()
    for filename in ('msvcp140.dll', 'vcruntime140.dll', 'vcruntime140_1.dll'):
        if not (crt / filename).is_file():
            parser.error('Missing x64 CRT file: ' + filename)
    name = 'Shaderixel-' + args.version + '-windows-x64-setup'
    output = ROOT / 'dist' / (name + '.exe')
    if output.exists():
        parser.error('Installer already exists; choose a new version or preserve the existing output first.')
    subprocess.run(['cmd', '/c', str(ROOT / 'build.bat'), 'Release'], cwd=ROOT, check=True)
    stage_root = ROOT / 'build/InstallerPayload' / args.version
    if stage_root.exists():
        parser.error('Installer staging folder already exists; choose a new version or preserve it first.')
    stage = stage_root / 'app'
    stage.mkdir(parents=True)
    # Explicit content list: runtime state, caches and machine-dependent demo guide
    # captures are not installed. The README uses the reviewed documentation images.
    for directory in CONTENT_DIRS:
        if (package / directory).is_dir():
            shutil.copytree(package / directory, stage / directory)
    for filename in BINARIES:
        shutil.copy2(ROOT / 'build/Release' / filename, stage / filename)
    for plugin in (stage / 'plugins').rglob('*.dll'):
        current = ROOT / 'build/Release/plugins' / plugin.relative_to(stage / 'plugins')
        if current.is_file():
            shutil.copy2(current, plugin)
    for filename in ('README.md', 'LICENSE'):
        shutil.copy2(ROOT / filename, stage / filename)
    shutil.copy2(ROOT / 'docs/PRESETS.md', stage / 'PRESETS.md')
    shutil.copytree(ROOT / 'docs/screenshots', stage / 'docs/screenshots')
    for guide in ('UI_UV_LIBRARY.md', 'UI_TOOLKIT.md'):
        target = stage / 'docs' / guide
        text = (ROOT / 'docs' / guide).read_text(encoding='utf-8')
        text = text.replace('../library/functions/', '../functions/')
        text = text.replace('../tools/', 'https://github.com/MrMybal/Shaderixel/blob/v' + args.version + '/tools/')
        target.write_text(text, encoding='utf-8')
    (stage / 'docs/images').mkdir(parents=True)
    for image in ('ui_uv_library.png', 'ui_toolkit.png'):
        shutil.copy2(ROOT / 'docs/images' / image, stage / 'docs/images' / image)
    for dll in crt.glob('*.dll'):
        shutil.copy2(dll, stage / dll.name)
    notice = ('Microsoft Visual C++ Runtime (x64)\n\n'
              'Copyright Microsoft Corporation. All rights reserved.\n'
              'These unmodified redistributable libraries retain their Microsoft license.\n'
              'https://visualstudio.microsoft.com/license-terms/\n'
              'https://learn.microsoft.com/cpp/windows/redistributing-visual-cpp-files\n')
    (stage / 'licences/Microsoft-Visual-C++-Runtime.txt').write_text(notice, encoding='utf-8')
    manifest = {p.relative_to(stage).as_posix(): digest(p) for p in sorted(stage.rglob('*')) if p.is_file()}
    (stage_root / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    command = [str(iscc), '/Qp', '/DPayloadDir=' + str(stage), '/DAppVersion=' + args.version,
               '/DOutputPath=' + str(ROOT / 'dist'), '/DOutputName=' + name, str(ROOT / 'installer/Shaderixel.iss')]
    subprocess.run(command, cwd=ROOT, check=True)
    checksum = output.with_suffix('.exe.sha256')
    checksum.write_text(digest(output) + '  ' + output.name + '\n', encoding='ascii')
    print('Installer: ' + str(output), flush=True)
    print('SHA-256: ' + digest(output), flush=True)


if __name__ == '__main__':
    main()

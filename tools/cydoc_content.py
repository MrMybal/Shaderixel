# These translations put an existing section earlier in the chapter. Match its
# meaning rather than assigning the English anchor by ordinal position.
FRENCH_SECTION_ORDER = {
    'getting_started':[3,0,1,2], 'masks':[3,0,1,2,4], 'color':[3,0,1,2,4],
    'smart_objects':[1,0,2], 'resources':[2,0,1,3],
}


def slug(value):
    return re.sub(r'[^a-z0-9]+', '-', fold(value)).strip('-') or 'page'


def fingerprint(value):
    return hashlib.sha256(value.replace('\r\n','\n').encode()).hexdigest()[:16]


def editions():
    return {language['code']: pages(language['code']) for language in languages()}


def translation_revisions(original, translated, registry):
    source=fingerprint(original['title']+'\n'+original['body'])
    acknowledged=registry.get(original['id'],{})
    target=fingerprint(translated['title']+'\n'+translated['body'])
    return source, acknowledged.get('source') if acknowledged.get('target')==target else None


def accept_translations(identifiers):
    data=editions()
    old=json.loads(REVISIONS.read_text(encoding='utf-8')) if REVISIONS.exists() else {}
    requested={p['id'] for p in data['en']} if identifiers==['all'] else set(identifiers)
    available={p['id'] for p in data['en']}
    if requested-available: raise ValueError('Unknown translation IDs: '+str(requested-available))
    for en,fr in zip(data['en'],data['fr']):
        if en['id'] in requested:
            old[en['id']]={'source':fingerprint(en['title']+'\n'+en['body']),
                           'target':fingerprint(fr['title']+'\n'+fr['body'])}
    REVISIONS.write_text(json.dumps(old,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')


def route_map(data):
    result = {p['id']: slug(p['id']) for p in data['en']}
    if len(set(result.values())) != len(result):
        raise ValueError('CyDoc page ID collision; add an explicit stable mapping.')
    return result


def common_anchors(data):
    result = {}
    for i, original in enumerate(data['en']):
        headings = re.findall(r'^#{1,6} (.+)', original['body'], re.M)
        anchors = []
        for title in headings:
            base = slug(title)
            name = base
            suffix = 2
            while name in anchors:
                name = base+'-'+str(suffix); suffix += 1
            anchors.append(name)
        for language, items in data.items():
            count = len(re.findall(r'^#{1,6} (.+)', items[i]['body'], re.M))
            if count != len(anchors):
                raise ValueError(f'{original["id"]}: align translated sections before migration ({language}).')
        result[original['id']] = anchors
    return result


def header(data, mapping):
    def lit(s): return json.dumps(s,ensure_ascii=False)
    lines = ['// Generated by tools/build_manual.py. CyDoc routes only; no reader or page bodies.',
             '#pragma once', '#include "ui/Documentation.h"', 'namespace sx::ui {',
             'inline constexpr ManualPage kManualPages[] = {']
    for p in data['en']:
        lines.append('    {'+', '.join(lit(v) for v in (p['id'],mapping[p['id']],p['title'],p['kind']))+'},')
    lines += ['};', 'inline constexpr ManualUiText kManualFunctionNames[] = {']
    lines += ['    {'+lit(p['sourceName'])+', '+lit(p['id'])+'},' for p in data['en'] if p['kind']=='Functions']
    lines += ['};', 'inline constexpr std::string_view kManualToolTopics[] = {']
    lines += ['    '+lit(p['id'])+',' for p in tool_catalog()]
    lines += ['};','inline constexpr ManualUiText kManualPanelTopics[] = {']
    lines += ['    {'+lit(name)+', '+lit(profile[0])+'},' for name,profile in panel_catalog().items()]
    lines += ['};','inline constexpr std::string_view kManualPracticeIds[] = {']
    lines += ['    '+lit(name)+',' for name in practice_files()]
    lines += ['};']
    for language in languages():
        code=language['code']
        lines += [f'inline constexpr ManualUiText kManualUi_{code}[] = {{']
        lines += ['    {'+lit(k)+', '+lit(v)+'},' for k,v in ui_strings()[code].items()]
        lines += ['};']
    lines += ['} // namespace sx::ui','']
    return '\n'.join(lines)


def graph_view(path, language, mapping):
    graph=json.loads(path.read_text(encoding='utf-8-sig'))['graph']
    nodes={str(n['id']):n for n in graph['nodes']}
    incoming={key:[] for key in nodes}; outgoing={key:{} for key in nodes}; links=[]
    for key,node in nodes.items():
        for i,value in enumerate(node.get('inputs',[])):
            if not value: continue
            # Serialized inputs encode a node ID; split outputs carry a separate
            # selector in the receiving node. This view documents connectivity.
            source=str(value if isinstance(value,int) else value.get('node',0))
            if source not in nodes: continue
            channels=node.get('inputChannels',[])
            selector=channels[i] if i<len(channels) else 0
            port='out-'+str(selector)
            channel=selector&7;output=selector>>3
            typ=str(nodes[source].get('value',{}).get('type','data')).lower()
            incoming[key].append({'id':'in-'+str(i),'label':('Input ' if language=='en' else 'Entrée ')+str(i),'type':typ})
            label=('Output ' if language=='en' else 'Sortie ')+str(output)
            if 0<channel<5:label+=' · '+'RGBA'[channel-1]
            outgoing[source][port]={'id':port,'label':label,'type':typ}
            links.append({'from':[source,port],'to':[key,'in-'+str(i)]})
        for pin,src,channel in node.get('execLinks',[]):
            source=str(src)
            if source not in nodes: raise ValueError('Invalid saved execution link: '+path.name)
            inp='exec-in-'+str(pin);out='exec-out-'+str(channel)
            if not any(p['id']==inp for p in incoming[key]):
                incoming[key].append({'id':inp,'label':'Exec '+str(pin),'type':'exec'})
            outgoing[source][out]={'id':out,'label':'Exec '+str(channel>>3),'type':'exec'}
            links.append({'from':[source,out],'to':[key,inp]})
    items=[]
    for key,node in nodes.items():
        pos=node.get('pos',[0,0]);effect=node.get('effect',{})
        ref=effect.get('effect') if isinstance(effect,dict) else None
        item={'id':key,'title':node.get('name') or ref or node['kind'],
              'x':float(pos[0]),'y':float(pos[1]),'inputs':incoming[key],
              'outputs':list(outgoing[key].values())}
        if ref and 'effect:'+ref in mapping: item['link']='doc:'+mapping['effect:'+ref]
        items.append(item)
    return {'id':'function-graph','title':path.stem,'nodes':items,'links':links}


def prepare():
    data=editions(); mapping=route_map(data); anchors=common_anchors(data)
    revisions=json.loads(REVISIONS.read_text(encoding='utf-8')) if REVISIONS.exists() else {}
    WORK.mkdir(parents=True,exist_ok=True)
    # Only generated directories owned by this tool may be replaced.
    for name in ('content','assets','sources'):
        target=(WORK/name).resolve()
        if not target.is_relative_to(WORK.resolve()): raise ValueError('Unsafe generated path')
        if target.exists(): shutil.rmtree(target)
        target.mkdir()
    config=json.loads(CONFIG.read_text(encoding='utf-8'))
    config['version']=(ROOT/'VERSION').read_text().strip()
    config['aliases']={old:new for old,new in mapping.items() if old!=new}
    for locale in config['locales']: (WORK/'content'/locale['code']).mkdir()
    downloads={}; extra={}; source_pages={}
    docs=[ROOT/'README.md',*sorted((ROOT/'docs').glob('*.md')),ROOT/'unreal/ShaderixelLink/README.md',
          *sorted((ROOT/'.claude/skills').glob('*/SKILL.md'))]
    for path in docs:
        source_pages[path.resolve()]='reference-'+slug(path.relative_to(ROOT).as_posix().removesuffix('.md'))
    for p in MANUAL.glob('[0-9][0-9]_*.md'):
        source_pages[p.resolve()]=mapping[p.stem[3:]]
        source_pages[(MANUAL/'fr'/p.name).resolve()]=mapping[p.stem[3:]]

    def asset(path):
        path=path.resolve()
        if not path.is_file() or not path.is_relative_to(ROOT): raise ValueError('Missing/unsafe documentation resource: '+str(path))
        relative=path.relative_to(ROOT).as_posix()
        destination=WORK/'assets'/relative
        destination.parent.mkdir(parents=True,exist_ok=True); shutil.copy2(path,destination)
        if path.suffix=='.png' and path.parent==MANUAL/'media' and path.with_suffix('.svg').is_file():
            shutil.copy2(path.with_suffix('.svg'),destination.with_suffix('.svg'))
        return 'assets/'+relative

    def download(path, page_id=None):
        path=path.resolve()
        ident=page_id or 'download-'+slug(path.relative_to(ROOT).as_posix())
        downloads[ident]={'src':asset(path),'filename':path.name}
        if not page_id: extra[ident]=path
        return ident

    def transform(body, language, legacy=None, origin=MANUAL):
        index=0; fenced=None; result=[]
        for line in body.splitlines():
            marker=re.match(r'^ {0,3}(`{3,}|~{3,})(.*)$',line)
            if fenced:
                if marker and marker[1][0]==fenced[0] and len(marker[1])>=fenced[1] and not marker[2].strip():fenced=None
                result.append(line);continue
            if marker:
                fenced=(marker[1][0],len(marker[1]));result.append(line);continue
            if legacy and re.match(r'^#{1,6} ',line):
                position=FRENCH_SECTION_ORDER.get(legacy,[])
                heading=position[index] if language=='fr' and position else index
                line+=' {#'+anchors[legacy][heading]+'}';index+=1
            picture=re.fullmatch(r'!\[([^\]]*)\]\(([^)]+)\)',line)
            if picture:
                path=(origin/picture[2]).resolve()
                media_id=slug(path.stem.removesuffix('_en').removesuffix('_fr'))
                result += ['```image',json.dumps({'id':media_id,'src':asset(path),'alt':picture[1],'controls':'minimal'},ensure_ascii=False),'```']
                continue
            def link(m):
                if any(code.start()<=m.start()<code.end() for code in re.finditer(r'(`+).*?\1',line)):
                    return m[0]
                label,target=m[1],m[2].removeprefix('<').removesuffix('>')
                if target.startswith('#') and target[1:] in mapping: return '['+label+'](doc:'+mapping[target[1:]]+')'
                if target.startswith('example:'): return '['+label+'](doc:practice-'+slug(target[8:])+'#download)'
                if re.match(r'^[a-z]+:|^#',target):return m[0]
                name,sep,anchor=unquote(target).partition('#');p=(origin/name).resolve()
                if p in source_pages:
                    return '['+label+'](doc:'+source_pages[p]+('#'+slug(anchor) if sep else '')+')'
                if p.is_file() and p.is_relative_to(ROOT):return '['+label+'](doc:'+download(p)+'#download)'
                # Relative resources must not silently disappear in CyDoc's safe URL filter.
                raise ValueError(f'Unresolved relative documentation link: {origin}: {target}')
            line=re.sub(r'(?<!!)\[([^\]]+)\]\(([^)]+)\)',link,line)
            result.append(line)
        return '\n'.join(result)

    def write(ident,title,body,language,section,order=0,revision=None,source_revision=None):
        fields={'id':ident,'title':title.replace('\n',' '),'description':title.replace('\n',' '),
                'section':section,'order':order}
        if revision:fields['revision']=revision
        if source_revision:fields['sourceRevision']=source_revision
        text='---\n'+'\n'.join(k+': '+str(v) for k,v in fields.items())+'\n---\n\n'+body.strip()+'\n'
        (WORK/'content'/language/(ident+'.md')).write_text(text,encoding='utf-8')

    sections={'Handbook':('Handbook','Manuel'),'Effects':('Effects','Effets'),'Functions':('Functions','Fonctions'),
              'Tools':('Tools','Outils'),'Commands':('Recorded commands','Commandes enregistrées'),
              'Brushes':('Brushes','Pinceaux'),'Nodes':('Node reference','Référence des nœuds')}
    for language,items in data.items():
        for i,page in enumerate(items):
            ident=mapping[page['id']];body=transform(page['body'],language,page['id'])
            revision,reviewed=translation_revisions(data['en'][i],data['fr'][i],revisions)
            if page['kind'] in ('Effects','Functions'):
                source=(ROOT/'shaders/effects'/(page['id'][7:]+'.slang') if page['kind']=='Effects'
                        else ROOT/'library/functions'/(page['id'][9:]+'.sxfn'))
                download(source,ident)
                body+='\n\n## '+('Source file' if language=='en' else 'Fichier source')+' {#source-file}\n\n'
                body+=('Download the shipped source below. Editing the downloaded copy does not change the bundled library.' if language=='en' else 'Téléchargez la source livrée ci-dessous. Modifier la copie téléchargée ne change pas la bibliothèque installée.')
                if page['kind']=='Functions':
                    body+='\n\n## '+('Interactive graph' if language=='en' else 'Graphe interactif')+' {#graph}\n\n'
                    body+=('Explore the actual saved connections. This reader does not evaluate shaders or execute tool events.' if language=='en' else 'Explorez les connexions réellement enregistrées. Ce lecteur ne calcule pas les shaders et ne lance pas les événements des outils.')
                    body+='\n\n```graph\n'+json.dumps(graph_view(source,language,mapping),ensure_ascii=False)+'\n```'
            related={'authoring':['docs/PRESETS.md'],
                     'plugins_bridge':['docs/PLUGINS.md','unreal/ShaderixelLink/README.md'],
                     'ui_textures':['docs/UI_UV_LIBRARY.md','docs/UI_TOOLKIT.md'],
                     'pbr':['docs/TEXTURES_PBR.md'],
                     'image_graph':['docs/GRAPH_LAYERS_EFFECTS.md']}.get(page['id'],[])
            if related:
                body+='\n\n## '+('Related references' if language=='en' else 'Références associées')+' {#related-references}\n\n'
                body+='\n'.join('- ['+Path(name).stem+'](doc:'+source_pages[(ROOT/name).resolve()]+')' for name in related)
                if page['id']=='plugins_bridge':body+='\n- [SDK ABI](doc:sdk-abi#loading)'
            write(ident,page['title'],body,language,sections[page['kind']][language=='fr'],i,
                  revision=revision if language=='en' else None,source_revision=reviewed if language=='fr' else None)

    # Preserve all existing developer/reference prose and code, with explicit
    # historical notices instead of treating a roadmap as implemented behavior.
    for path in docs:
        if path.resolve() not in source_pages:continue
        body=path.read_text(encoding='utf-8-sig')
        title=re.search(r'^# (.+)',body,re.M)[1]
        ident=source_pages[path.resolve()]
        historical=path.name in ('ROADMAP.md','MANUAL_MILESTONES.md','legacy_test_guide.fr.md')
        source_fr=path.name in ('ARCHITECTURE.md','PLUGINS.md','PRESETS.md','ROADMAP.md') or path.stem.endswith('.fr')
        notice=('Historical project record. Items described as planned are not a promise of current application behavior. ' if historical else '')
        notice+='Preserved repository reference: `'+path.relative_to(ROOT).as_posix()+'`.'
        en=notice+'\n\n'+('The original reference below is in French. The [handbook](doc:getting-started) is available in English and French; this appendix has not been translated.\n\n' if source_fr else '')
        en+=transform(body,'en',origin=path.parent)
        write(ident,title,en,'en','Repository references',2000,revision=fingerprint(body))
        if source_fr:
            fr=('Document historique : les éléments prévus ne décrivent pas tous des fonctions disponibles.\n\n' if historical else '')+transform(body,'fr',origin=path.parent)
            # This is the preserved French original, not a reviewed translation of the English wrapper.
            write(ident,title,fr,'fr','Références du dépôt',2000)

    for name,content in practice_files().items():
        path=MANUAL/'examples'/(name+'.sxl');path.parent.mkdir(exist_ok=True);path.write_bytes(content)
        ident='practice-'+slug(name);download(path,ident)
        for language in ('en','fr'):
            body=('Download this editable Shaderixel practice document. Open your downloaded copy with File > Open. Opening a tool graph does not run its events. The application also offers Help > Practice projects, which opens an unsaved copy.' if language=='en' else 'Téléchargez ce projet modifiable puis ouvrez votre copie avec Fichier > Ouvrir. Ouvrir un graphe outil ne lance pas ses événements. Aide > Projets d’exercice ouvre aussi une copie non enregistrée.')
            body+='\n\n## '+('Download project' if language=='en' else 'Télécharger le projet')+' {#download}'
            write(ident,ui_strings()[language][name],body,language,'Practice projects' if language=='en' else 'Projets d’exercice',2100,revision='1' if language=='en' else None,source_revision='1' if language=='fr' else None)
    for ident,path in extra.items():
        for language in ('en','fr'):
            body=('Preserved local resource: ' if language=='en' else 'Ressource locale conservée : ')+path.relative_to(ROOT).as_posix()+'\n\n## '+('Download' if language=='en' else 'Télécharger')+' {#download}'
            write(ident,path.name,body,language,'Downloads' if language=='en' else 'Téléchargements',2200,revision='1' if language=='en' else None,source_revision='1' if language=='fr' else None)
    # Public SDK only. Never index src/, build/, external/, credentials or local configuration.
    shutil.copytree(ROOT/'sdk',WORK/'sources/sdk',ignore=shutil.ignore_patterns('build','__pycache__','*.dll','*.pdb','*.lib','*.exp'))
    (WORK/'assets/favicon.svg').write_text('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="7" fill="#252333"/><path d="M24 8H12a5 5 0 0 0 0 10h8a3 3 0 0 1 0 6H8" fill="none" stroke="#a38aff" stroke-width="4"/></svg>')
    ROUTES.write_text(header(data,mapping),encoding='utf-8')
    (WORK/'cydoc.config.json').write_text(json.dumps(config,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (WORK/'shaderixel-options.json').write_text(json.dumps({'downloads':downloads,'aliases':config['aliases'],'theme':'midnight','storageId':'shaderixel-help'},ensure_ascii=False),encoding='utf-8')
    coverage={'reader':'CyDoc','languages':['en','fr'],'pagesPerLanguage':len(data['en']),
              'catalogs':{k:sum(p['kind']==k for p in data['en']) for k in sections},
              'illustrations':len(media_assets(data)),'practiceDocuments':len(practice_files()),
              'panelsAndDialogs':len(panel_catalog()),'modules':config['modules'],
              'sourceIndexScope':['sdk/include','sdk/examples'],'repositoryReferences':len(docs),
              'compiledNodeSources':json.loads((MANUAL/'locales/node_catalog.json').read_text(encoding='utf-8'))['sources']}
    (MANUAL/'coverage.json').write_text(json.dumps(coverage,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return data,coverage

def slug(value):
    return re.sub(r'[^a-z0-9]+', '-', fold(value)).strip('-') or 'page'


def fingerprint(value):
    return hashlib.sha256(value.replace('\r\n','\n').encode()).hexdigest()[:16]


def editions():
    return {language['code']: pages(language['code']) for language in languages()}


def translation_revisions(original, translated, registry):
    source=fingerprint(original['title']+'\n'+original['body'])
    acknowledged=registry.get(original['id'],{})
    target=fingerprint(translated['title']+'\n'+translated['body'])
    return source, acknowledged.get('source') if acknowledged.get('target')==target else None


def accept_translations(identifiers):
    data=editions()
    old=json.loads(REVISIONS.read_text(encoding='utf-8')) if REVISIONS.exists() else {}
    requested={p['id'] for p in data['en']} if identifiers==['all'] else set(identifiers)
    available={p['id'] for p in data['en']}
    if requested-available: raise ValueError('Unknown translation IDs: '+str(requested-available))
    for en,fr in zip(data['en'],data['fr']):
        if en['id'] in requested:
            old[en['id']]={'source':fingerprint(en['title']+'\n'+en['body']),
                           'target':fingerprint(fr['title']+'\n'+fr['body'])}
    REVISIONS.write_text(json.dumps(old,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')


def route_map(data):
    result = {p['id']: slug(p['id']) for p in data['en']}
    if len(set(result.values())) != len(result):
        raise ValueError('CyDoc page ID collision; add an explicit stable mapping.')
    return result


def common_anchors(data):
    result = {}
    for i, original in enumerate(data['en']):
        headings = re.findall(r'^#{1,6} (.+)', original['body'], re.M)
        anchors = []
        for title in headings:
            explicit=re.search(r' \{#([^}]+)\}$',title)
            base = explicit[1] if explicit else slug(title)
            name = base
            suffix = 2
            while name in anchors:
                name = base+'-'+str(suffix); suffix += 1
            anchors.append(name)
        for language, items in data.items():
            count = len(re.findall(r'^#{1,6} (.+)', items[i]['body'], re.M))
            if count != len(anchors):
                raise ValueError(f'{original["id"]}: align translated sections before migration ({language}).')
        result[original['id']] = anchors
    return result


def header(data, mapping):
    def lit(s): return json.dumps(s,ensure_ascii=False)
    lines = ['// Generated by .CyDocBuild/build_manual.py. CyDoc routes only; no reader or page bodies.',
             '#pragma once', '#include "ui/Documentation.h"', 'namespace sx::ui {',
             'inline constexpr ManualPage kManualPages[] = {']
    for p in data['en']:
        lines.append('    {'+', '.join(lit(v) for v in (p['id'],mapping[p['id']],p['title'],p['kind']))+'},')
    lines += ['};', 'inline constexpr ManualUiText kManualFunctionNames[] = {']
    lines += ['    {'+lit(p['sourceName'])+', '+lit(p['id'])+'},' for p in data['en'] if p['kind']=='Functions']
    lines += ['};', 'inline constexpr std::string_view kManualToolTopics[] = {']
    lines += ['    '+lit(p['id'])+',' for p in tool_catalog()]
    lines += ['};','inline constexpr ManualUiText kManualPanelTopics[] = {']
    lines += ['    {'+lit(name)+', '+lit(profile[0])+'},' for name,profile in panel_catalog().items()]
    lines += ['};','inline constexpr std::string_view kManualPracticeIds[] = {']
    lines += ['    '+lit(name)+',' for name in practice_files()]
    lines += ['};']
    for language in languages():
        code=language['code']
        lines += [f'inline constexpr ManualUiText kManualUi_{code}[] = {{']
        lines += ['    {'+lit(k)+', '+lit(v)+'},' for k,v in ui_strings()[code].items()]
        lines += ['};']
    lines += ['} // namespace sx::ui','']
    return '\n'.join(lines)


def graph_view(path, language, mapping):
    graph=json.loads(path.read_text(encoding='utf-8-sig'))['graph']
    nodes={str(n['id']):n for n in graph['nodes']}
    incoming={key:[] for key in nodes}; outgoing={key:{} for key in nodes}; links=[]
    for key,node in nodes.items():
        for i,value in enumerate(node.get('inputs',[])):
            if not value: continue
            # Serialized inputs encode a node ID; split outputs carry a separate
            # selector in the receiving node. This view documents connectivity.
            source=str(value if isinstance(value,int) else value.get('node',0))
            if source not in nodes: continue
            channels=node.get('inputChannels',[])
            selector=channels[i] if i<len(channels) else 0
            port='out-'+str(selector)
            channel=selector&7;output=selector>>3
            typ=str(nodes[source].get('value',{}).get('type','data')).lower()
            incoming[key].append({'id':'in-'+str(i),'label':('Input ' if language=='en' else 'Entrée ')+str(i),'type':typ})
            label=('Output ' if language=='en' else 'Sortie ')+str(output)
            if 0<channel<5:label+=' · '+'RGBA'[channel-1]
            outgoing[source][port]={'id':port,'label':label,'type':typ}
            links.append({'from':[source,port],'to':[key,'in-'+str(i)]})
        for pin,src,channel in node.get('execLinks',[]):
            source=str(src)
            if source not in nodes: raise ValueError('Invalid saved execution link: '+path.name)
            inp='exec-in-'+str(pin);out='exec-out-'+str(channel)
            if not any(p['id']==inp for p in incoming[key]):
                incoming[key].append({'id':inp,'label':'Exec '+str(pin),'type':'exec'})
            outgoing[source][out]={'id':out,'label':'Exec '+str(channel>>3),'type':'exec'}
            links.append({'from':[source,out],'to':[key,inp]})
    items=[]
    for key,node in nodes.items():
        pos=node.get('pos',[0,0]);effect=node.get('effect',{})
        ref=effect.get('effect') if isinstance(effect,dict) else None
        title=node.get('name') or ref or node['kind']
        if language=='fr' and title!=ref:
            title=french_label(title)
        elif language=='en':
            title=english_label(title)
        item={'id':key,'title':title,
              'x':float(pos[0]),'y':float(pos[1]),'inputs':incoming[key],
              'outputs':list(outgoing[key].values())}
        if ref and 'effect:'+ref in mapping: item['link']='doc:'+mapping['effect:'+ref]
        items.append(item)
    return {'id':'function-graph','title':french_label(path.stem) if language=='fr' else english_label(path.stem),'nodes':items,'links':links}



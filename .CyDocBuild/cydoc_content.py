def frontmatter(path):
    text=path.read_text(encoding='utf-8')
    head,body=text[4:].split('\n---\n',1)
    return dict(line.split(': ',1) for line in head.splitlines() if ': ' in line),body.strip()


def write_page(ident,title,description,body,language,section,parent=None,order=0,revision=None,filename=None):
    fields={'id':ident,'title':title,'description':description,'section':section,'order':order}
    if parent:fields['parent']=parent
    if revision:fields['revision' if language=='en' else 'sourceRevision']=revision
    path=MANUAL/language/(filename or 'generated-'+ident+'.md')
    path.write_text('---\n'+'\n'.join(k+': '+str(v).replace('\n',' ') for k,v in fields.items())+'\n---\n\n'+body.strip()+'\n',encoding='utf-8')


